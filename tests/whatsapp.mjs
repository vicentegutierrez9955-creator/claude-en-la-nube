// Prueba del webhook y del envío de WhatsApp, en memoria y sin llamar a Meta. Uso: node tests/whatsapp.mjs
import { createHmac } from 'node:crypto';
Object.assign(process.env, { PANEL_STORE: 'memory', WHATSAPP_APP_SECRET: 'secreto', WHATSAPP_VERIFY_TOKEN: 'verifica', WHATSAPP_TOKEN: 'tk', WHATSAPP_PHONE_NUMBER_ID: '111', PANEL_API_TOKEN: 'api' });
const enviados = [];
globalThis.fetch = async (u, o) => { enviados.push({ u: String(u), b: JSON.parse(o.body) }); return new Response(JSON.stringify({ messages: [{ id: 'wamid.S' + enviados.length }] })); };
const { default: hook } = await import('../api/whatsapp/webhook.js');
const { default: panel } = await import('../api/panel/whatsapp.js');
const ok = (c, m) => { console.log(c ? 'OK  ' : 'FALLA', m); if (!c) process.exitCode = 1; };
const H = 'https://sitio.test';
const firmar = (s) => 'sha256=' + createHmac('sha256', 'secreto').update(s).digest('hex');
const avisar = (value, firma) => { const b = JSON.stringify({ entry: [{ changes: [{ value }] }] }); return hook.fetch(new Request(H + '/api/whatsapp/webhook', { method: 'POST', body: b, headers: { 'x-hub-signature-256': firma ?? firmar(b) } })); };
const msg = (id, texto) => ({ contacts: [{ wa_id: '56962333569', profile: { name: 'Vicente' } }], messages: [{ id, from: '56962333569', timestamp: '1792400000', type: 'text', text: { body: texto } }] });
const estado = async () => (await panel.fetch(new Request(H + '/api/panel/whatsapp?t=api&accion=estado'))).json();

let r = await hook.fetch(new Request(H + '/api/whatsapp/webhook?hub.mode=subscribe&hub.verify_token=verifica&hub.challenge=123'));
ok(r.status === 200 && (await r.text()) === '123', 'verificación: devuelve el challenge con el token correcto');
r = await hook.fetch(new Request(H + '/api/whatsapp/webhook?hub.mode=subscribe&hub.verify_token=otro&hub.challenge=123'));
ok(r.status === 403, 'verificación: rechaza un token incorrecto');
ok((await avisar(msg('w1', 'hola'), 'sha256=malo')).status === 401, 'rechaza avisos sin firma válida');
ok((await avisar(msg('w1', 'Hola'))).status === 200 && enviados.length === 1 && enviados[0].b.to === '56962333569' && enviados[0].b.text.body.includes('STPyme'), 'responde a "hola"');
await avisar(msg('w1', 'Hola'));
ok(enviados.length === 1, 'no repite si Meta reenvía el mismo mensaje');
await avisar(msg('w2', 'quiero saber el precio'));
ok(enviados.length === 1, 'no responde solo a cualquier mensaje');
await avisar(msg('w3', 'SALIR'));
let e = await estado();
ok(e.bajas === 1 && enviados.at(-1).b.text.body.includes('VOLVER'), 'SALIR: registra la baja y confirma');
await avisar(msg('w4', 'volver'));
ok((await estado()).bajas === 0, 'VOLVER: quita la baja');
await avisar(msg('w5', 'Eliminar mis datos'));
e = await estado();
ok(e.eliminarPendientes === 1 && enviados.at(-1).b.text.body.includes('30 días'), 'ELIMINAR: registra la solicitud y confirma');
await avisar({ statuses: [{ id: 'wamid.S1', status: 'read' }] });
e = await estado();
ok(e.mensajes.find((m) => m.id === 'wamid.S1')?.estado === 'read', 'actualiza el estado de un mensaje enviado');
ok(e.mensajes.find((m) => m.id === 'w2')?.nombre === 'Vicente' && e.configurado.WHATSAPP_TOKEN === true, 'el estado muestra mensajes y configuración');
r = await panel.fetch(new Request(H + '/api/panel/whatsapp?t=api&accion=enviar&para=56962333569&plantilla=hello_world&idioma=en_US'));
ok(r.status === 200 && enviados.at(-1).b.template.name === 'hello_world' && enviados.at(-1).u.endsWith('/111/messages'), 'envía una plantilla desde Claude');
ok((await panel.fetch(new Request(H + '/api/panel/whatsapp?t=mala&accion=estado'))).status === 401, 'el panel exige clave o sesión');
ok((await panel.fetch(new Request(H + '/api/panel/whatsapp?accion=enviar&para=56962333569&texto=x'))).status === 401, 'sin sesión no envía');
